class TopicProfile:
    def __init__(self, data: Dict[str, Any]) -> None:
        self.topic: str = str(data.get("topic") or "")
        self.source: str = str(data.get("source") or "builtin")
        self.strong_terms: List[str] = list(data.get("strong_terms") or [])
        self.support_terms: List[str] = list(data.get("support_terms") or [])
        self.hard_negative: List[str] = list(data.get("hard_negative") or [])
        self.soft_negative: List[str] = list(data.get("soft_negative") or [])
        self.slots: List[Slot] = [
            Slot(
                title=str(s.get("title") or ""),
                intent=str(s.get("intent") or ""),
                keywords=list(s.get("keywords") or []),
            )
            for s in (data.get("slots") or [])
        ]
        self.filter_dimensions: Dict[str, List[Dict[str, Any]]] = data.get("filter_dimensions") or {}
        self.required_space_terms: List[str] = []  # set by apply_filter_dimensions when space constraints detected
        self.generated_at: str = str(data.get("generated_at") or "")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "topic": self.topic,
            "source": self.source,
        "generated_at": self.generated_at,
        "strong_terms": self.strong_terms,
        "support_terms": self.support_terms,
        "hard_negative": self.hard_negative,
        "soft_negative": self.soft_negative,
        "filter_dimensions": self.filter_dimensions,
        "slots": [
            {"title": s.title, "intent": s.intent, "keywords": s.keywords}
            for s in self.slots
            ],
        }

    def needs_filter(self) -> bool:
        """Return True when the profile has enough terms to act as a content gate."""
        return bool(self.strong_terms or self.support_terms)


# ---------------------------------------------------------------------------
# Profile registry / cache
# ---------------------------------------------------------------------------

_MEMORY: Dict[str, TopicProfile] = {}


def _profiles_dir(data_root: Path) -> Path:
    p = data_root / "topic_profiles"
    p.mkdir(parents=True, exist_ok=True)
    return p


def _topic_slug(topic: str) -> str:
    return slugify(topic) or "generic"


def _normalize_topic_key(topic: str) -> str:
    return re.sub(r"[\s_\-/]+", "", topic.strip().lower())


def _find_builtin_profile(topic: str) -> Optional[Dict[str, Any]]:
    key = _normalize_topic_key(topic)
    alias_map = {_normalize_topic_key(alias): profile_key for alias, profile_key in _BUILTIN_ALIASES.items()}
    profile_key = alias_map.get(key)
    if profile_key:
        return _BUILTIN_PROFILES[profile_key]

    for alias, profile_key in sorted(alias_map.items(), key=lambda item: len(item[0]), reverse=True):
        if alias and alias in key:
            return _BUILTIN_PROFILES[profile_key]
    return None


def load_profile(topic: str, data_root: Path, ai_api_key: Optional[str] = None) -> TopicProfile:
    """
    Return a TopicProfile for *topic*.

    Resolution order:
    1. In-memory cache (same process)
    2. Built-in profiles for common Bilibili domains
    3. Cached JSON in data/topic_profiles/<slug>.json
    4. AI-generated (calls OpenAI if api_key supplied)
    5. Falls back to generic profile
    """
    slug = _topic_slug(topic)

    if slug in _MEMORY:
        return _MEMORY[slug]

    # Built-in exact/alias/subtopic match
    builtin_data = _find_builtin_profile(topic)
    if builtin_data:
        profile = TopicProfile({**builtin_data, "topic": topic, "generated_at": ""})
        _MEMORY[slug] = profile
        return profile

    # Cached on disk
    cache_path = _profiles_dir(data_root) / f"{slug}.json"
    if cache_path.exists():
        try:
            data = json.loads(cache_path.read_text(encoding="utf-8"))
            profile = TopicProfile(data)
            _MEMORY[slug] = profile
            return profile
        except (json.JSONDecodeError, KeyError):
            cache_path.unlink(missing_ok=True)

    # AI generation
    if ai_api_key:
        try:
            profile = _generate_via_ai(topic, ai_api_key)
            profile.generated_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
            cache_path.write_text(
                json.dumps(profile.to_dict(), ensure_ascii=False, indent=2),
                encoding="utf-8",
            )
            _MEMORY[slug] = profile
            return profile
        except Exception:
            pass  # fall through to generic

    # Generic fallback
    profile = TopicProfile({**_BUILTIN_GENERIC, "topic": topic})
    _MEMORY[slug] = profile
    return profile


def invalidate_profile(topic: str, data_root: Path) -> None:
    """Delete cached profile so it will be regenerated on next load."""
    slug = _topic_slug(topic)
    _MEMORY.pop(slug, None)
    cache_path = _profiles_dir(data_root) / f"{slug}.json"
    cache_path.unlink(missing_ok=True)


