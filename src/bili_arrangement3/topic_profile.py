_SYSTEM_PROMPT = """\
You are a content classification assistant. Given a topic, produce a JSON object
(no markdown fences, raw JSON only) with exactly these fields:

{
  "strong_terms": [...],   // 15-25 terms: strong signals that a video IS practice/tutorial content for this topic
  "support_terms": [...],  // 10-15 softer signals (≥2 needed alongside a topic keyword)
  "hard_negative": [...],  // 5-10 terms: always reject (meta, behind-paywall, stream replays)
  "soft_negative": [...],  // 10-20 terms: reject if in title without a strong signal (vlogs, announcements, etc.)
  "slots": [               // exactly 7 weekly slots, each with title, intent, keywords[]
    {"title": "...", "intent": "...", "keywords": ["..."]}
  ]
}

Rules:
- All terms/keywords must be lowercase.
- Terms should work against concatenated title+description text.
- Slots should form a logical weekly progression for the topic.
- Respond with raw JSON only.
"""


def _generate_via_ai(topic: str, api_key: str) -> TopicProfile:
    """Call OpenAI chat completions to generate a profile for *topic*."""
    base_url = os.environ.get("OPENAI_BASE_URL", "https://api.openai.com").rstrip("/")
    model = os.environ.get("OPENAI_MODEL", "gpt-4o-mini")
    payload = json.dumps({
        "model": model,
        "temperature": 0.3,
        "messages": [
            {"role": "system", "content": _SYSTEM_PROMPT},
            {"role": "user", "content": f"Topic: {topic}"},
        ],
    }).encode()
    req = urllib.request.Request(
        f"{base_url}/v1/chat/completions",
        data=payload,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
        },
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        body = json.loads(resp.read().decode())
    content = body["choices"][0]["message"]["content"].strip()
    # Strip markdown fences if present
    content = re.sub(r"^```[a-z]*\n?", "", content)
    content = re.sub(r"\n?```$", "", content)
    data = json.loads(content)
    data["topic"] = topic
    data["source"] = "ai"
    return TopicProfile(data)
